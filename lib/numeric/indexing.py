"""
Индексация мономов и базисных элементов W_n^{(k)}.

Все мультииндексы — кортежи (tuple) длины n.
Результаты кешируются для повторного использования.
"""

from __future__ import annotations

from functools import lru_cache
from math import comb
from typing import Dict, List, Tuple

import numpy as np


# ---------------------------------------------------------------------------
# Перечисление мультииндексов
# ---------------------------------------------------------------------------

@lru_cache(maxsize=512)
def multiindices(n: int, s: int) -> Tuple[Tuple[int, ...], ...]:
    """
    Перечислить все мультииндексы фиксированной суммарной степени.

    На вход принимает число переменных ``n`` и суммарную степень ``s``.
    На выходе возвращает кортеж всех ``alpha in Z_{>= 0}^n`` с ``|alpha| = s`` в лексикографическом порядке.

    >>> multiindices(2, 2)
    ((2, 0), (1, 1), (0, 2))
    """
    if n == 1:
        return ((s,),)
    result: List[Tuple[int, ...]] = []
    for first in range(s, -1, -1):
        for tail in multiindices(n - 1, s - first):
            result.append((first,) + tail)
    return tuple(result)


@lru_cache(maxsize=512)
def multiindex_lookup(n: int, s: int) -> Dict[Tuple[int, ...], int]:
    """
    Построить обратное отображение от мультииндекса к его позиции.

    На вход принимает число переменных ``n`` и суммарную степень ``s``.
    На выходе возвращает словарь ``alpha -> index`` согласованный с ``multiindices(n, s)``.

    >>> multiindex_lookup(2, 2)[(1, 1)]
    1
    """
    return {alpha: idx for idx, alpha in enumerate(multiindices(n, s))}


# ---------------------------------------------------------------------------
# Размерности
# ---------------------------------------------------------------------------

def num_monomials(n: int, s: int) -> int:
    """
    Вычислить число мономов фиксированной степени в ``n`` переменных.

    На вход принимает число переменных ``n`` и степень ``s``.
    На выходе возвращает биномиальное число ``C(s + n - 1, n - 1)``.

    >>> num_monomials(3, 2)
    6
    """
    if s < 0:
        return 0
    return comb(s + n - 1, n - 1)


def dim_Wn_k(n: int, k: int) -> int:
    """
    Вычислить размерность однородной компоненты ``W_n^(k)``.

    На вход принимает число переменных ``n`` и степень ``k``.
    На выходе возвращает ``n * C(k + n, n - 1)`` для ``k >= -1`` и ``0`` иначе.

    >>> dim_Wn_k(2, 1)
    6
    """
    if k < -1:
        return 0
    return n * comb(k + n, n - 1)


def dim_Wn_leq_d(n: int, d: int) -> int:
    """
    Вычислить суммарную размерность усечённой алгебры ``W_n^(<= d)``.

    На вход принимает число переменных ``n`` и верхнюю степень ``d``.
    На выходе возвращает сумму размерностей компонент степеней от ``-1`` до ``d``.

    >>> dim_Wn_leq_d(2, 2)
    20
    """
    if d < -1:
        return 0
    return n * comb(d + n + 1, n)


# ---------------------------------------------------------------------------
# Индексация базиса W_n^{(k)}
# ---------------------------------------------------------------------------

def basis_index(alpha: Tuple[int, ...], i: int, n: int, k: int) -> int:
    """
    Закодировать базисный элемент ``z^alpha * d/dz_i`` индексом в ``W_n^(k)``.

    На вход принимает мультииндекс ``alpha`` с ``|alpha| = k + 1``, индекс компоненты ``i``, размерность ``n`` и степень ``k``.
    На выходе возвращает индекс в диапазоне ``[0, dim_Wn_k(n, k))``.

    >>> basis_index((1, 1), 1, 2, 1)
    4
    """
    s = k + 1  # |α| должен быть s
    lookup = multiindex_lookup(n, s)
    m = len(lookup)  # = num_monomials(n, s)
    return i * m + lookup[alpha]


def decode_basis_index(idx: int, n: int, k: int) -> Tuple[Tuple[int, ...], int]:
    """
    Декодировать индекс базиса обратно в мультииндекс и ось.

    На вход принимает индекс ``idx``, размерность ``n`` и степень ``k``.
    На выходе возвращает пару ``(alpha, i)``, соответствующую базисному элементу ``z^alpha * d/dz_i``.

    >>> decode_basis_index(4, 2, 1)
    ((1, 1), 1)
    """
    s = k + 1
    monoms = multiindices(n, s)
    m = len(monoms)
    i = idx // m
    alpha = monoms[idx % m]
    return alpha, i


# ---------------------------------------------------------------------------
# Вспомогательные numpy-утилиты
# ---------------------------------------------------------------------------

def unit_vector(n: int) -> np.ndarray:
    """
    Построить матрицу стандартного базиса в ``R^n``.

    На вход принимает размерность ``n``.
    На выходе возвращает матрицу ``n x n``, строки которой равны стандартным единичным векторам.

    >>> unit_vector(3).tolist()
    [[1, 0, 0], [0, 1, 0], [0, 0, 1]]
    """
    return np.eye(n, dtype=np.int64)


_UNIT_CACHE: Dict[int, np.ndarray] = {}


def e_vec(i: int, n: int) -> np.ndarray:
    """
    Вернуть ``i``-й стандартный единичный вектор длины ``n``.

    На вход принимает индекс ``i`` и размерность ``n``.
    На выходе возвращает кешированный numpy-вектор с единственной единицей на позиции ``i``.

    >>> e_vec(1, 3).tolist()
    [0, 1, 0]
    """
    if n not in _UNIT_CACHE:
        _UNIT_CACHE[n] = np.eye(n, dtype=np.int64)
    return _UNIT_CACHE[n][i]
